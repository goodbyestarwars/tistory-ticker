const fs = require('fs');
const path = require('path');
const vm = require('vm');
const assert = require('assert');
const src = fs.readFileSync(process.argv[2] || path.join(__dirname, '../js/investor-flow.js'), 'utf8');
const window = {NineUI: {escapeHtml: v => String(v).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/"/g,'&quot;')}};
vm.runInNewContext(src, {window});
const render = window.InvestorFlow.miniBars;
const future = render([], {unit:'contracts', market:'KOSPI200 선물 전체', snapshot:{frgn:2729,orgn:-2483,ind:2}});
assert(future.includes('+2,729계약'));
assert(future.includes('−2,483계약'));
assert(future.includes('절대계약수'));
assert(future.includes('width:100.00%'));
assert(future.includes('width:90.99%'));
assert(!future.includes('억'));
const partial = render([], {unit:'contracts', snapshot:{frgn:0,orgn:null,ind:''}});
assert(partial.includes('0계약'));
assert.equal((partial.match(/미관측/g)||[]).length, 2);
const equity = render([{slot:0,asOf:'2026-11-13T09:05:00+09:00',frgn:10,orgn:-5,ind:0}], {date:'2026-11-13',market:'KOSPI'});
assert(equity.includes('+10억'));
assert(!equity.includes('계약'));
assert(render([], {date:'2026-11-13'}).includes('장중 저장 관측값 없음'));
console.log('PASS futures units/scale/missing/zero and existing equity defaults');
