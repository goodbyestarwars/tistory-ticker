const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const context = {};
vm.createContext(context);
vm.runInContext(fs.readFileSync('js/scanner-progress.js', 'utf8'), context);
const model = context.ScannerProgress.model;
const run = {id:'dailyscan', lastExecution:{state:'running'}, progress:{processed:25,total:100,phase:'일봉',updatedAt:'2026-10-26T12:00:00Z'}};
assert.equal(model([run], false, Date.parse('2026-10-26T12:01:00Z')).percent,25);
assert.equal(model([{id:'dailyscan',lastExecution:{state:'running'}}],false,0).percent,null);
assert.equal(model([{id:'dailyscan',lastExecution:{state:'failed'}}],false,0).percent,null);
assert.equal(model([{id:'dailyscan',lastExecution:{state:'success'}}],false,0).percent,100);
assert.equal(model([run,{id:'strategyscan',lastExecution:{state:'waiting'}}],true,Date.parse('2026-10-26T12:05:00Z')).stale,true);
assert.equal(model([{...run,progress:{processed:101,total:100}}],false,0).percent,null);
assert.equal(model([{...run,progress:{processed:100,total:100,updatedAt:'2026-10-26T12:00:00Z'}}],false,Date.parse('2026-10-26T12:01:00Z')).percent,99);
console.log('Scanner progress states passed');

const late=Date.parse('2026-10-26T16:00:00Z');
const old=model([{id:'dailyscan',lastExecution:{state:'running',startedAt:'2026-10-26T11:10:06Z'},progress:null}],false,late);
assert.equal(old.state,'unverified');assert.equal(old.percent,null);assert.ok(!old.title.includes('진행 중'));assert.ok(old.note.includes('완료 여부 확인 불가'));
assert.equal(model([run],false,Date.parse('2026-10-26T12:05:00Z')).state,'unverified');
assert.equal(model([{id:'dailyscan',lastExecution:{state:'running',startedAt:'2026-10-26T12:00:00Z'}}],false,Date.parse('2026-10-26T12:01:00Z')).state,'running');
assert.equal(model([{id:'dailyscan',lastExecution:{state:'success',finishedAt:'2026-10-26T12:00:00Z'}}],false,late).state,'success');
assert.equal(model([{id:'strategyscan',contract:{maxWait:60},lastExecution:{state:'waiting',queuedAt:'2026-10-26T12:00:00Z'}}],true,late).state,'unverified');
assert.equal(model([{...run,progress:{processed:1}}],false,late).state,'unverified');
