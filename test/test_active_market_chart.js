const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync('js/stock-search.js', 'utf8');
const start = source.indexOf('  function activeStockChartElement(container) {');
const end = source.indexOf('\n  function renderChartForCode(', start);
let fullscreen = null;
const context = {document: {querySelector: () => fullscreen}};
vm.createContext(context);
vm.runInContext(source.slice(start, end), context);
const select = context.activeStockChartElement;
const chart = hidden => ({closest: () => hidden ? {} : null});
const us = chart(true), domestic = chart(false);
const root = {querySelectorAll: () => [us, domestic]};
assert.equal(select(root), domestic, 'US -> domestic skips retained hidden chart');
us.closest = () => null;
domestic.closest = () => ({});
assert.equal(select(root), us, 'domestic -> US chooses visible chart');
assert.equal(select({querySelectorAll: () => [chart(true)]}), null);
assert.equal(select(null), null);
fullscreen = chart(false);
assert.equal(select(root), fullscreen, 'fullscreen chart retains priority');
console.log('PASS active market chart host: both directions, hidden, missing, fullscreen');
