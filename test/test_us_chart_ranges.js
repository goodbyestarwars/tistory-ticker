const assert = require('assert');
const data = require('../js/chart-data.js');
const wrap = {dataset:{}, innerHTML:'', hidden:true, querySelector(){return {textContent:''};}};
const parent = {querySelector(){return wrap;}};
const chart = {parentElement:parent};
let rerendered = 0;
global.fetch = () => {throw Error('US range must not call the Korean history API');};
const bars = [{date:'2024-10-20'}, {date:'2026-10-19'}];
data.installRangeButtons(chart, 'US:INTC', () => ({daily:bars}), () => {rerendered++;});
assert(wrap.innerHTML.includes('data-range="1m"'));
assert(wrap.innerHTML.includes('data-range="all"'));
assert(!wrap.innerHTML.includes('data-range="3y"'));
assert(!wrap.innerHTML.includes('data-range="5y"'));
assert.equal(wrap.hidden, false);
wrap.onclick({target:{closest:()=>({getAttribute:()=> 'all'})}});
assert.equal(rerendered, 1);
assert.deepEqual(data.rangeDates(bars, 'US:INTC'), {from:'2024-10-20',to:'2026-10-19'});
data.installRangeButtons(chart, '042660', () => ({daily:bars}), () => {});
assert(wrap.innerHTML.includes('data-range="3y"'));
assert(wrap.innerHTML.includes('data-range="5y"'));
console.log('PASS US range controls, no Korean API request, coverage clamp, Korean extended periods preserved');
